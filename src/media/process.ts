// Upload processing: ffprobe the source, then make what the official player
// consumes, in two stages so an upload can be watched within seconds.
//
// publish: one muxed MP4 the player can start with, then the video is
//   playable (status stays 'processing' until the ladder is done).
//   - an H.264 source (8-bit 4:2:0) is remuxed, not re-encoded: the video
//     stream is copied, AAC audio too (other audio becomes AAC, no audio
//     becomes silence), at itag 18/22/37 by height
//   - anything else gets a fast 360p encode at itag 18
//   - thumbnails at YouTube's names and sizes, and three stills (at a
//     quarter, half and three quarters) for Studio's thumbnail picker
// ladder: everything else, in the background, added format by format.
//   - itag 18: progressive MP4 (H.264 + AAC, 360p), if publish didn't make it
//   - DASH video: fragmented MP4 with a global sidx, one per rung of the
//     ladder up to the source height, streamingData.adaptiveFormats
//   - itag 140: fragmented AAC audio, 128 kb/s; itag 251: Opus in WebM
//   - every video rung twice: H.264/MP4 (Safari, Chrome) and VP9/WebM
//     (Chromium builds without proprietary codecs, Firefox)
//
// Jobs run in this process from the processing_jobs queue, claimed with
// `for update skip locked` by a small pool of workers (PROCESSING_WORKERS,
// default 2) plus one that only takes publish jobs, so a long ladder never
// holds up a new upload.

