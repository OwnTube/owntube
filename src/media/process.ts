// YouTube's itags: H.264 in MP4 (Safari, Chrome) and VP9 in WebM (Firefox,
// Chromium builds without proprietary codecs), one of each per rung
type Rung = { height: number; itag: number; itag60?: number; vp9: number; vp960?: number; quality: string; maxrate: number };
const LADDER: Rung[] = [
	{ height: 144, itag: 160, vp9: 278, quality: "tiny", maxrate: 150 },
	{ height: 240, itag: 133, vp9: 242, quality: "small", maxrate: 400 },
	{ height: 360, itag: 134, vp9: 243, quality: "medium", maxrate: 800 },
	{ height: 480, itag: 135, vp9: 244, quality: "large", maxrate: 1400 },
	{ height: 720, itag: 136, itag60: 298, vp9: 247, vp960: 302, quality: "hd720", maxrate: 3000 },
	{ height: 1080, itag: 137, itag60: 299, vp9: 248, vp960: 303, quality: "hd1080", maxrate: 5500 },
];

const THUMBS = [
	{ name: "default", w: 120, h: 90 },
	{ name: "mqdefault", w: 320, h: 180 },
	{ name: "hqdefault", w: 480, h: 360 },
	{ name: "sddefault", w: 640, h: 480 },
	{ name: "maxresdefault", w: 1280, h: 720 },
	{ name: "hq720", w: 1280, h: 720 },
];
// the whole frame at the video's own aspect, up to 1080x1920 (the Shorts player's poster)
const FRAME0 = { name: "frame0", w: 1080, h: 1920 };
// Studio's autogenerated stills, numbered as its thumbnail picker names them
export const STILLS = [1, 2, 3] as const;
const STILL_AT = { 1: 0.25, 2: 0.5, 3: 0.75 } as const;

const WORKERS = Math.max(1, Math.min(16, Number(process.env.PROCESSING_WORKERS) || 2));

export type Probe = {
	duration: number;
	width: number;
	height: number;
	fps: number;
	hasAudio: boolean;
	rotation: number;
	vcodec: string;
	pixFmt: string;
	acodec: string | null;
	sampleRate: number | null;
	channels: number | null;
};

async function run(cmd: string[], timeoutMs = 60 * 60 * 1000): Promise<string> {
	const p = Bun.spawn(cmd, { stdout: "pipe", stderr: "pipe" });
	const timer = setTimeout(() => p.kill(), timeoutMs);
	const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
	clearTimeout(timer);
	if (code !== 0) throw new Error(`${cmd[0] === "nice" ? cmd[3] : cmd[0]} exited ${code}: ${err.trim().split("\n").slice(-3).join(" ")}`);
	return out;
}
// the ladder's encodes yield the CPU to publish jobs and the server
const background = (cmd: string[]) => run(["nice", "-n", "10", ...cmd]);

export async function probe(path: string): Promise<Probe> {
	const out = JSON.parse(await run(["ffprobe", "-v", "error", "-print_format", "json", "-show_format", "-show_streams", path], 60_000));
	const v = (out.streams ?? []).find((s: any) => s.codec_type === "video" && !s.disposition?.attached_pic);
	if (!v) throw new Error("the file has no video stream");
	const a = (out.streams ?? []).find((s: any) => s.codec_type === "audio");
	const duration = Number(out.format?.duration ?? v.duration);
	if (!(duration > 0)) throw new Error("could not read the duration");
	const [num, den] = String(v.avg_frame_rate || v.r_frame_rate || "30/1").split("/").map(Number);
	const fps = den ? num / den : 30;
	const rotation = Math.abs(Number(v.side_data_list?.find((d: any) => d.rotation !== undefined)?.rotation ?? v.tags?.rotate ?? 0)) % 180;
	const [width, height] = rotation === 90 ? [v.height, v.width] : [v.width, v.height];
	return {
		duration,
		width,
		height,
		fps: Number.isFinite(fps) && fps > 0 ? fps : 30,
		hasAudio: !!a,
		rotation,
		vcodec: String(v.codec_name ?? ""),
		pixFmt: String(v.pix_fmt ?? ""),
		acodec: a ? String(a.codec_name ?? "") : null,
		sampleRate: a ? Number(a.sample_rate) || null : null,
		channels: a ? Number(a.channels) || null : null,
	};
}

const even = (n: number) => Math.max(2, Math.round(n / 2) * 2);

// what browsers play from a copied stream: 8-bit 4:2:0 H.264 at up to 60 fps
export const canRemux = (p: Probe) => p.vcodec === "h264" && (p.pixFmt === "yuv420p" || p.pixFmt === "yuvj420p") && p.fps <= 61 && p.width <= 4096 && p.height <= 4096;

// YouTube's muxed itags by height, with the player's quality names
function muxedFormat(height: number, fps: number) {
	const label = (h: number) => `${h}p${Math.round(fps) > 30 ? Math.round(fps) : ""}`;
	if (height <= 360) return { itag: 18, quality: height <= 144 ? "tiny" : height <= 240 ? "small" : "medium", qualityLabel: label(height) };
	if (height <= 720) return { itag: 22, quality: height <= 480 ? "large" : "hd720", qualityLabel: label(height) };
	return { itag: 37, quality: height <= 1080 ? "hd1080" : height <= 1440 ? "hd1440" : "hd2160", qualityLabel: label(height) };
}

type Out = { itag: number; kind: "muxed" | "video" | "audio"; path: string; quality: string; qualityLabel?: string; height?: number };

// the video_formats rows for files in dir
async function describe(videoId: string, dir: string, outs: Out[], p: Probe, fps: number) {
	const rows = [];
	for (const f of outs) {
		const full = join(dir, f.path);
		const size = statSync(full).size;
		const fp = await probe(full).catch(() => undefined);
		const bitrate = Math.round((size * 8) / p.duration);
		const webm = f.path.endsWith(".webm");
		const ranges = f.kind === "muxed" ? undefined : webm ? webmRanges(full) : dashRanges(full);
		let mime: string;
		if (webm) mime = f.kind === "video" ? 'video/webm; codecs="vp9"' : 'audio/webm; codecs="opus"';
		else if (f.kind === "muxed") mime = `video/mp4; codecs="${codecString(full)}, mp4a.40.2"`;
		else if (f.kind === "video") mime = `video/mp4; codecs="${codecString(full)}"`;
		else mime = `audio/mp4; codecs="${codecString(full)}"`;
		rows.push({
			video_id: videoId,
			itag: f.itag,
			kind: f.kind,
			mime_type: mime,
			path: join(videoId, f.path),
			size,
			bitrate: Math.round(bitrate * 1.2),
			average_bitrate: bitrate,
			width: f.kind === "audio" ? null : (fp?.width ?? null),
			height: f.kind === "audio" ? null : (fp?.height ?? f.height),
			fps: f.kind === "audio" ? null : fps,
			quality: f.quality,
			quality_label: f.qualityLabel ?? null,
			init_start: ranges?.initStart ?? null,
			init_end: ranges?.initEnd ?? null,
			index_start: ranges?.indexStart ?? null,
			index_end: ranges?.indexEnd ?? null,
			audio_sample_rate: f.kind === "video" ? null : webm ? 48000 : (fp?.sampleRate ?? 44100),
			audio_channels: f.kind === "video" ? null : (fp?.channels ?? 2),
			duration_ms: Math.round(p.duration * 1000),
		});
	}
	return rows;
}

function silence(p: Probe) {
	// the silence is endless: -shortest and -t bound it to the video
	return p.hasAudio
		? { input: [], map: ["-map", "0:a:0"] }
		: { input: ["-f", "lavfi", "-i", "anullsrc=channel_layout=stereo:sample_rate=44100"], map: ["-map", "1:a:0", "-shortest", "-t", p.duration.toFixed(3)] };
}

// the 360p progressive MP4 (itag 18)
async function encode360(src: string, dir: string, p: Probe, runner = run): Promise<Out> {
	const fps = Math.min(60, Math.round(p.fps));
	const a = silence(p);
	await runner(["ffmpeg", "-v", "error", "-y", "-i", src, ...a.input, "-map", "0:v:0", ...a.map, "-vf", `scale=-2:${Math.min(360, even(p.height))}`, "-r", String(fps),
		"-c:v", "libx264", "-profile:v", "main", "-preset", "veryfast", "-crf", "26", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "96k", "-ac", "2", "-ar", "44100", "-movflags", "+faststart", join(dir, "18.mp4")]);
	return { itag: 18, kind: "muxed", path: "18.mp4", quality: "medium", qualityLabel: "360p", height: Math.min(360, even(p.height)) };
}

// the source's own H.264 stream in a progressive MP4, with AAC audio
async function remux(src: string, dir: string, p: Probe): Promise<Out> {
	const a = silence(p);
	const audio = p.acodec === "aac" ? ["-c:a", "copy"] : ["-c:a", "aac", "-b:a", "128k", "-ac", "2", "-ar", "44100"];
	const f = muxedFormat(p.height, p.fps);
	const file = `${f.itag}.mp4`;
	await run(["ffmpeg", "-v", "error", "-y", "-i", src, ...a.input, "-map", "0:v:0", ...a.map, "-c:v", "copy", ...audio, "-movflags", "+faststart", "-f", "mp4", join(dir, file)]);
	return { ...f, kind: "muxed", path: file, height: p.height };
}

async function ladder(src: string, dir: string, p: Probe, has18: boolean): Promise<Out[]> {
	const fps = Math.min(60, Math.round(p.fps));
	const gop = Math.max(1, fps * 2);
	const outFps = ["-r", String(fps)];
	const a = silence(p);
	const outs: Out[] = [];
	if (!has18) outs.push(await encode360(src, dir, p, background));
	for (const r of LADDER) {
		if (r.height > p.height && r.height !== 144) continue;
		const itag = fps > 30 && r.itag60 ? r.itag60 : r.itag;
		const file = `${itag}.mp4`;
		await background(["ffmpeg", "-v", "error", "-y", "-i", src, "-map", "0:v:0", "-an", "-vf", `scale=-2:${r.height}`, ...outFps,
			"-c:v", "libx264", "-profile:v", r.height >= 720 ? "high" : "main", "-preset", "veryfast", "-crf", "23", "-maxrate", `${r.maxrate}k`, "-bufsize", `${r.maxrate * 2}k`,
			"-pix_fmt", "yuv420p", "-g", String(gop), "-keyint_min", String(gop), "-sc_threshold", "0",
			"-movflags", "+frag_keyframe+empty_moov+default_base_moof+global_sidx", "-f", "mp4", join(dir, file)]);
		outs.push({ itag, kind: "video", path: file, quality: r.quality, qualityLabel: `${r.height}p${fps > 30 ? fps : ""}`, height: r.height });
		const vp9 = fps > 30 && r.vp960 ? r.vp960 : r.vp9;
		await background(["ffmpeg", "-v", "error", "-y", "-i", src, "-map", "0:v:0", "-an", "-vf", `scale=-2:${r.height}`, ...outFps,
			"-c:v", "libvpx-vp9", "-deadline", "realtime", "-cpu-used", "8", "-row-mt", "1", "-crf", "33", "-b:v", `${r.maxrate}k`, "-maxrate", `${r.maxrate}k`, "-bufsize", `${r.maxrate * 2}k`,
			"-pix_fmt", "yuv420p", "-g", String(gop), "-keyint_min", String(gop), "-f", "webm", "-dash", "1", "-cues_to_front", "1", join(dir, `${vp9}.webm`)]);
		outs.push({ itag: vp9, kind: "video", path: `${vp9}.webm`, quality: r.quality, qualityLabel: `${r.height}p${fps > 30 ? fps : ""}`, height: r.height });
	}
	await background(["ffmpeg", "-v", "error", "-y", "-i", src, ...a.input, "-vn", ...a.map, "-c:a", "aac", "-b:a", "128k", "-ac", "2", "-ar", "44100",
		"-frag_duration", "2000000", "-movflags", "+empty_moov+default_base_moof+global_sidx", "-f", "mp4", join(dir, "140.m4a")]);
	outs.push({ itag: 140, kind: "audio", path: "140.m4a", quality: "tiny" });
	await background(["ffmpeg", "-v", "error", "-y", "-i", src, ...a.input, "-vn", ...a.map, "-c:a", "libopus", "-b:a", "128k", "-ac", "2",
		"-f", "webm", "-dash", "1", "-cues_to_front", "1", join(dir, "251.webm")]);
	outs.push({ itag: 251, kind: "audio", path: "251.webm", quality: "tiny" });
	return outs;
}

// ---- thumbnails ----

// the size of w x h scaled down to fit in maxW x maxH, in even pixels
function fit(w: number, h: number, maxW: number, maxH: number): [number, number] {
	const s = Math.min(1, maxW / w, maxH / h);
	return [Math.trunc((w * s) / 2) * 2, Math.trunc((h * s) / 2) * 2];
}

// 4:3 names are letterboxed like YouTube's; 16:9 ones are cropped to fill
const box = (w: number, h: number) =>
	w / h > 1.5
		? `scale=${w}:${h}:force_original_aspect_ratio=increase,crop=${w}:${h}`
		: `scale=${w}:${h}:force_original_aspect_ratio=decrease,pad=${w}:${h}:(ow-iw)/2:(oh-ih)/2:black`;

export const stillFile = (n: number) => `still${n}.jpg`;
export const CUSTOM_THUMBNAIL = "custom.jpg";

// a frame at each still's time, whole, fitted into 1280x720 (Studio's
// picker expects that size, and the thumbnails are made from it)
async function stills(src: string, dir: string, p: Probe) {
	const fill = "scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2:black";
	await Promise.all(
		STILLS.map((n) => run(["ffmpeg", "-v", "error", "-y", "-ss", (p.duration * STILL_AT[n]).toFixed(2), "-i", src, "-frames:v", "1", "-vf", fill, "-q:v", "2", join(dir, stillFile(n))])),
	);
	// the Shorts poster: the first still, whole, up to 1080x1920
	const [fw, fh] = fit(p.width, p.height, FRAME0.w, FRAME0.h);
	await run(["ffmpeg", "-v", "error", "-y", "-ss", (p.duration * STILL_AT[1]).toFixed(2), "-i", src, "-frames:v", "1", "-vf", `scale=${fw}:${fh}`, "-q:v", "3", join(dir, "frame0.jpg")]);
	return { name: FRAME0.name, file: "frame0.jpg", width: fw, height: fh };
}

// YouTube's thumbnail names rendered from one image (a still or a custom
// upload); `tag` makes the file names new, so a changed choice isn't served
// from a cache under the old name
async function renderThumbs(image: string, dir: string, tag = "") {
	await Promise.all(THUMBS.map((t) => run(["ffmpeg", "-v", "error", "-y", "-i", image, "-frames:v", "1", "-vf", box(t.w, t.h), "-q:v", "3", join(dir, `${t.name}${tag}.jpg`)])));
	return THUMBS.map((t) => ({ name: t.name, file: `${t.name}${tag}.jpg`, width: t.w, height: t.h }));
}

const thumbSource = (choice: string) => (choice === "custom" ? CUSTOM_THUMBNAIL : /^still[123]$/.test(choice) ? `${choice}.jpg` : stillFile(1));

// sets a video's thumbnail from its stills or its custom upload: choice is
// still1-3, custom or auto (the first still)
export async function applyThumbnail(videoId: string, choice: string) {
	const dir = join(MEDIA_DIR, videoId);
	const image = join(dir, thumbSource(choice));
	if (!existsSync(image)) throw new Error("that thumbnail isn't available");
	const tag = `-${Date.now().toString(36)}`;
	const thumbs = await renderThumbs(image, dir, tag);
	const old = (await sql`select path from video_thumbnails where video_id = ${videoId} and name <> ${FRAME0.name}`) as { path: string }[];
	await sql.begin(async (tx) => {
		for (const t of thumbs) {
			await tx`insert into video_thumbnails (video_id, name, path, width, height) values (${videoId}, ${t.name}, ${join(videoId, t.file)}, ${t.width}, ${t.height})
				on conflict (video_id, name) do update set path = excluded.path, width = excluded.width, height = excluded.height`;
		}
		await tx`update videos set thumbnail_choice = ${choice} where id = ${videoId}`;
	});
	for (const o of old) if (!thumbs.some((t) => join(videoId, t.file) === o.path)) rmSync(join(MEDIA_DIR, o.path), { force: true });
}

// stills for a video processed before they were made, from its kept source
const making = new Map<string, Promise<void>>();
export function ensureStills(videoId: string, source: string | null) {
	const dir = join(MEDIA_DIR, videoId);
	if (STILLS.every((n) => existsSync(join(dir, stillFile(n)))) || !source || !existsSync(source) || !existsSync(dir)) return Promise.resolve();
	let p = making.get(videoId);
	if (!p) {
		p = (async () => {
			const work = join(MEDIA_DIR, `.stills-${videoId}`);
			mkdirSync(work, { recursive: true });
			try {
				await stills(source, work, await probe(source));
				for (const n of STILLS) renameSync(join(work, stillFile(n)), join(dir, stillFile(n)));
			} finally {
				rmSync(work, { recursive: true, force: true });
			}
		})()
			.catch((e) => console.log(`stills for ${videoId} failed: ${e instanceof Error ? e.message : e}`))
			.finally(() => making.delete(videoId));
		making.set(videoId, p);
	}
	return p;
}

// ---- stages ----

async function sourceOf(videoId: string) {
	const [video] = await sql`select id, source_path, deleted_at, playable, thumbnail_choice from videos where id = ${videoId}`;
	if (!video || video.deleted_at) return undefined;
	if (!video.source_path || !existsSync(video.source_path)) throw new Error("the uploaded file is missing");
	return video as { id: string; source_path: string; playable: boolean; thumbnail_choice: string };
}

// deleted while it was processing
async function dropIfDeleted(videoId: string) {
	const [gone] = await sql`select 1 from videos where id = ${videoId} and deleted_at is not null`;
	if (gone) deleteMedia(videoId);
	return !!gone;
}

async function publish(videoId: string) {
	const video = await sourceOf(videoId);
	if (!video) return;
	await sql`update videos set status = 'processing', error = null where id = ${videoId}`;
	const finalDir = join(MEDIA_DIR, videoId);
	const work = join(MEDIA_DIR, `.work-${videoId}`);
	rmSync(work, { recursive: true, force: true });
	mkdirSync(work, { recursive: true });
	try {
		const p = await probe(video.source_path);
		if (p.duration > 6 * 3600) throw new Error("videos are limited to 6 hours");
		if (p.width < 16 || p.height < 16) throw new Error("the video is too small");
		const first = canRemux(p) ? await remux(video.source_path, work, p).catch(() => encode360(video.source_path, work, p)) : await encode360(video.source_path, work, p);
		const [formats, frame0] = await Promise.all([describe(videoId, work, [first], p, Math.round(p.fps)), stills(video.source_path, work, p)]);
		// a custom thumbnail outlives processing it again
		const custom = join(finalDir, CUSTOM_THUMBNAIL);
		if (existsSync(custom)) copyFileSync(custom, join(work, CUSTOM_THUMBNAIL));
		const choice = video.thumbnail_choice === "custom" && !existsSync(custom) ? "auto" : video.thumbnail_choice;
		const thumbs = [...(await renderThumbs(join(work, thumbSource(choice)), work)), frame0];
		rmSync(finalDir, { recursive: true, force: true });
		renameSync(work, finalDir);
		forgetFormats(videoId);
		await sql.begin(async (tx) => {
			await tx`delete from video_formats where video_id = ${videoId}`;
			await tx`delete from video_thumbnails where video_id = ${videoId}`;
			for (const f of formats) await tx`insert into video_formats ${tx(f)}`;
			for (const t of thumbs) await tx`insert into video_thumbnails ${tx({ video_id: videoId, name: t.name, path: join(videoId, t.file), width: t.width, height: t.height })}`;
			await tx`update videos set playable = true, status = 'processing', thumbnail_choice = ${choice}, duration_ms = ${Math.round(p.duration * 1000)}, width = ${p.width}, height = ${p.height}, fps = ${p.fps},
				published_at = case when visibility <> 'private' and not draft then coalesce(published_at, now()) else published_at end where id = ${videoId}`;
			await tx`insert into processing_jobs (video_id, stage) values (${videoId}, 'ladder')`;
		});
		if (!(await dropIfDeleted(videoId))) poke();
	} catch (e) {
		rmSync(work, { recursive: true, force: true });
		throw e;
	}
}

async function buildLadder(videoId: string) {
	const video = await sourceOf(videoId);
	if (!video) return;
	const finalDir = join(MEDIA_DIR, videoId);
	const work = join(MEDIA_DIR, `.ladder-${videoId}`);
	rmSync(work, { recursive: true, force: true });
	mkdirSync(work, { recursive: true });
	try {
		const p = await probe(video.source_path);
		const [{ has18 }] = await sql`select exists(select 1 from video_formats where video_id = ${videoId} and itag = 18) as has18`;
		const outs = await ladder(video.source_path, work, p, has18);
		const formats = await describe(videoId, work, outs, p, Math.min(60, Math.round(p.fps)));
		if (await dropIfDeleted(videoId)) return;
		mkdirSync(finalDir, { recursive: true });
		for (const o of outs) renameSync(join(work, o.path), join(finalDir, o.path));
		await sql.begin(async (tx) => {
			await tx`delete from video_formats where video_id = ${videoId} and itag in ${tx(formats.map((f) => f.itag))}`;
			for (const f of formats) await tx`insert into video_formats ${tx(f)}`;
			await tx`update videos set status = 'ready', error = null where id = ${videoId}`;
		});
		forgetFormats(videoId);
		await dropIfDeleted(videoId);
	} finally {
		rmSync(work, { recursive: true, force: true });
	}
}

// ---- the queue ----

type Stage = "publish" | "ladder";
const STAGES: Stage[] = ["publish", "ladder"];

// runs the oldest waiting job (publish jobs first) of the given stages;
// false when there was none
export async function runQueueOnce(stages: Stage[] = STAGES): Promise<boolean> {
	const [job] = await sql`update processing_jobs set state = 'running', started_at = now(), attempts = attempts + 1
		where id = (select j.id from processing_jobs j where j.state = 'queued' and j.stage in ${sql(stages)}
			and not exists(select 1 from processing_jobs r where r.video_id = j.video_id and r.state = 'running')
			order by j.stage = 'publish' desc, j.created_at limit 1 for update skip locked)
		returning id, video_id, stage`;
	if (!job) return false;
	const t0 = Date.now();
	try {
		if (job.stage === "publish") await publish(job.video_id);
		else await buildLadder(job.video_id);
		await sql`update processing_jobs set state = 'done', finished_at = now() where id = ${job.id}`;
		console.log(`processed ${job.video_id} (${job.stage}) in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
	} catch (e) {
		const msg = e instanceof Error ? e.message : String(e);
		console.log(`processing ${job.video_id} (${job.stage}) failed: ${msg}`);
		await sql`update processing_jobs set state = 'failed', error = ${msg}, finished_at = now() where id = ${job.id}`;
		// a video that can already be watched stays up; the ladder is retried by processing it again
		await sql`update videos set status = case when playable then 'ready' else 'failed' end, error = ${msg.slice(0, 500)} where id = ${job.video_id}`;
	}
	return true;
}

// idle workers wait for a poke (a new job) or two seconds
const idle = new Set<() => void>();
function nap(ms: number) {
	return new Promise<void>((resolve) => {
		const done = () => {
			clearTimeout(timer);
			idle.delete(done);
			resolve();
		};
		const timer = setTimeout(done, ms);
		idle.add(done);
	});
}
function poke() {
	for (const f of [...idle]) f();
}

async function worker(stages: Stage[]) {
	for (;;) {
		const ran = await runQueueOnce(stages).catch((e) => {
			console.log(`processing queue: ${e instanceof Error ? e.message : e}`);
			return false;
		});
		if (!ran) await nap(2000);
	}
}

export async function startProcessing() {
	// jobs left running by a stopped server start over
	await sql`update processing_jobs set state = 'queued' where state = 'running'`;
	await sql`update videos set status = 'queued' where status = 'processing' and not playable`;
	if (existsSync(MEDIA_DIR)) for (const f of readdirSync(MEDIA_DIR, { withFileTypes: true })) if (f.isDirectory() && /^\.(work|ladder|stills)-/.test(f.name)) rmSync(join(MEDIA_DIR, f.name), { recursive: true, force: true });
	for (let i = 0; i < WORKERS; i++) void worker(STAGES);
	// new uploads never wait behind the ladders
	void worker(["publish"]);
}

// processes the video (again) from its source; one that can already be
// watched stays up meanwhile
export async function enqueue(videoId: string) {
	await sql.begin(async (tx) => {
		await tx`delete from processing_jobs where video_id = ${videoId} and state = 'queued'`;
		await tx`update videos set status = case when playable then status else 'queued' end where id = ${videoId}`;
		await tx`insert into processing_jobs (video_id, stage) values (${videoId}, 'publish')`;
	});
	poke();
}

// a deleted video's encodes, work directories and uploaded source
export function deleteMedia(videoId: string) {
	forgetFormats(videoId);
	rmSync(join(MEDIA_DIR, videoId), { recursive: true, force: true });
	rmSync(join(MEDIA_DIR, "sources", `${videoId}.src`), { force: true });
	for (const w of ["work", "ladder", "stills"]) rmSync(join(MEDIA_DIR, `.${w}-${videoId}`), { recursive: true, force: true });
}
